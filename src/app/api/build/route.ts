import { NextResponse } from "next/server";
import { getServerSession } from "next-auth";
import { authOptions } from "@/lib/auth";
import {
  buildRepoContext,
  runCodegen,
} from "@/lib/codegen";
import { commitFilesToNewBranch } from "@/lib/github";

export const dynamic = "force-dynamic";
export const maxDuration = 300;

interface BuildRequestBody {
  owner?: string;
  repo?: string;
  prompt?: string;
  model?: string;
  apiKey?: string;
  baseUrl?: string;
  branchName?: string;
  openPr?: boolean;
  temperature?: number;
}

export async function POST(req: Request) {
  const session = await getServerSession(authOptions);
  if (!session?.accessToken) {
    return NextResponse.json(
      { error: "Not authenticated with GitHub" },
      { status: 401 },
    );
  }

  let body: BuildRequestBody;
  try {
    body = (await req.json()) as BuildRequestBody;
  } catch {
    return NextResponse.json({ error: "Invalid JSON body" }, { status: 400 });
  }

  const { owner, repo, prompt, model, apiKey } = body;
  if (!owner || !repo) {
    return NextResponse.json(
      { error: "owner and repo are required" },
      { status: 400 },
    );
  }
  if (!prompt || prompt.trim().length === 0) {
    return NextResponse.json(
      { error: "prompt is required" },
      { status: 400 },
    );
  }
  if (!model) {
    return NextResponse.json({ error: "model is required" }, { status: 400 });
  }
  if (!apiKey) {
    return NextResponse.json(
      { error: "CloseRouter apiKey is required" },
      { status: 400 },
    );
  }

  try {
    const context = await buildRepoContext({
      accessToken: session.accessToken,
      owner,
      repo,
    });
    const generation = await runCodegen({
      apiKey,
      baseUrl: body.baseUrl,
      model,
      userPrompt: prompt,
      context,
      owner,
      repo,
      temperature: body.temperature,
    });

    const ts = Math.floor(Date.now() / 1000);
    const branchName =
      body.branchName?.trim() || `gma-codegen/${ts}-${slugify(prompt)}`;
    const commitMessage = `gma-codegen: ${truncate(prompt, 60)}`;
    const prTitle = `gma-codegen: ${truncate(prompt, 60)}`;
    const prBody = [
      "Generated by gma-codegen.",
      "",
      `**Model:** \`${model}\``,
      "",
      "**User prompt:**",
      "```",
      prompt,
      "```",
      "",
      "**Model summary:**",
      generation.summary || "(no summary provided)",
      "",
      "**Files changed:**",
      ...generation.files.map((f) => `- \`${f.path}\``),
    ].join("\n");

    const commit = await commitFilesToNewBranch({
      accessToken: session.accessToken,
      owner,
      repo,
      baseBranch: context.branch,
      newBranch: branchName,
      files: generation.files,
      commitMessage,
      prTitle,
      prBody,
      openPr: body.openPr !== false,
    });

    return NextResponse.json({
      ok: true,
      branch: commit.branch,
      commitSha: commit.commitSha,
      prUrl: commit.prUrl,
      prNumber: commit.prNumber,
      summary: generation.summary,
      files: generation.files.map((f) => ({
        path: f.path,
        bytes: Buffer.byteLength(f.content, "utf-8"),
      })),
    });
  } catch (err) {
    return NextResponse.json(
      {
        ok: false,
        error: err instanceof Error ? err.message : "Unknown error",
      },
      { status: 500 },
    );
  }
}

function slugify(s: string): string {
  return s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 32) || "task";
}

function truncate(s: string, n: number): string {
  const flat = s.replace(/\s+/g, " ").trim();
  return flat.length <= n ? flat : flat.slice(0, n - 1) + "…";
}
